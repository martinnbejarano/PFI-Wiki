"""Índice local de fuentes oficiales del Módulo 3 (ticket #108, PRD #107).

La evidencia oficial es la de mayor peso de la jerarquía, y por la búsqueda web
llega con la misma latencia y la misma caja negra que los medios. Este índice
guarda fragmentos de documentos oficiales recientes y devuelve los más cercanos
al texto de la publicación, que el adaptador del LLM le entrega a su única
llamada como un bloque de documentos.

El esquema es el del modelo de datos del capítulo 4, en la misma base que el
histórico y la memoria (`app/base_de_datos.py`), con `pgvector`:

- `fuente_oficial`: el catálogo, con su dominio, su demora de rastreo y la
  fecha de la última corrida y, si el sitio respondió 429, hasta cuándo no se
  le pide nada. Lo llena la ingesta (#109, `app/ingesta.py`).
- `documento`: un fragmento por fila, con su texto, la URL de origen, el título
  del documento, la fecha de publicación, la fuente del catálogo y su
  *embedding*. La ingesta da de alta la fuente antes de guardar sus fragmentos.

Los fragmentos se embeben con el mismo embebedor que la memoria, que memoriza el
último texto: la memoria y el índice comparten un solo pedido a `/embeber` por
análisis. Cualquier falla sale como `ErrorDelProveedor`, igual que en el
embebedor, para que quien consulta tenga una sola excepción que atajar.
"""

from __future__ import annotations

from dataclasses import dataclass

import psycopg
from psycopg_pool import ConnectionPool

from ..base_de_datos import abrir, vector
from .memoria import DIMENSIONES, Embebedor
from .puerto import ErrorDelProveedor

# ponytail: búsqueda exacta sobre toda la tabla, sin índice HNSW; con decenas
# de miles de fragmentos y latencia a la vista, `USING hnsw (embedding vector_cosine_ops)`.
ESQUEMA = f"""
CREATE EXTENSION IF NOT EXISTS vector;
CREATE TABLE IF NOT EXISTS fuente_oficial (
    nombre           TEXT PRIMARY KEY,
    dominio          TEXT NOT NULL,
    demora_rastreo_s DOUBLE PRECISION NOT NULL,
    ultima_corrida   TEXT,
    pausa_hasta      TEXT
);
-- Las bases anteriores a la pausa por 429.
ALTER TABLE fuente_oficial ADD COLUMN IF NOT EXISTS pausa_hasta TEXT;
CREATE TABLE IF NOT EXISTS documento (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuente            TEXT NOT NULL REFERENCES fuente_oficial (nombre),
    url               TEXT NOT NULL,
    titulo            TEXT NOT NULL,
    fecha_publicacion TEXT NOT NULL,
    texto             TEXT NOT NULL,
    embedding         vector({DIMENSIONES}) NOT NULL
);
CREATE INDEX IF NOT EXISTS documento_url ON documento(url);
"""


@dataclass(frozen=True)
class Fragmento:
    """Un fragmento de un documento oficial. `fecha_publicacion` va en ISO
    (`AAAA-MM-DD`) y `fuente` es el nombre de la fila de `fuente_oficial`."""

    texto: str
    url: str
    titulo: str
    fecha_publicacion: str
    fuente: str


class IndiceDeFuentes:
    """Fragmentos oficiales con su *embedding*, consultables por similitud."""

    def __init__(self, url: str, embebedor: Embebedor) -> None:
        self.embebedor = embebedor
        # Si la base no responde, el índice queda inactivo: cada consulta
        # falla y el análisis sigue sin el bloque. El servicio arranca igual.
        self._pool = None
        self._error_al_abrir = ""
        try:
            self._pool = abrir(url, ESQUEMA)
        except psycopg.Error as error:
            self._error_al_abrir = str(error)

    def agregar(self, fragmentos: list[Fragmento]) -> None:
        """Embebe y guarda los fragmentos. Lo usa la ingesta (#109)."""
        pool = self._activo()
        vectores = [vector(self.embebedor.embeber(f.texto)) for f in fragmentos]
        try:
            with pool.connection() as conexion:
                conexion.cursor().executemany(
                    "INSERT INTO documento "
                    "(fuente, url, titulo, fecha_publicacion, texto, embedding) "
                    "VALUES (%s, %s, %s, %s, %s, %s)",
                    [(f.fuente, f.url, f.titulo, f.fecha_publicacion, f.texto, v)
                     for f, v in zip(fragmentos, vectores)],
                )
        except psycopg.Error as error:
            raise ErrorDelProveedor(f"indice | {error}") from error

    def buscar(self, texto: str, k: int) -> list[tuple[Fragmento, float]]:
        """Los `k` fragmentos más cercanos al texto, con su similitud coseno,
        del más cercano al más lejano. El umbral lo aplica quien consulta."""
        pool = self._activo()
        consulta = vector(self.embebedor.embeber(texto))
        try:
            with pool.connection() as conexion:
                filas = conexion.execute(
                    f"""
                    SELECT texto, url, titulo, fecha_publicacion, fuente,
                           embedding <=> %s::vector({DIMENSIONES}) AS distancia
                    FROM documento ORDER BY distancia LIMIT %s
                    """,
                    (consulta, k),
                ).fetchall()
        except psycopg.Error as error:
            raise ErrorDelProveedor(f"indice | {error}") from error
        return [(Fragmento(*fila[:5]), 1.0 - fila[5]) for fila in filas]

    # -- Lo que usa la ingesta (#109) --------------------------------------

    def indexada(self, url: str) -> bool:
        """Si ya hay fragmentos de esa URL: la ingesta no la vuelve a bajar."""
        return self._consultar(
            "SELECT 1 FROM documento WHERE url = %s LIMIT 1", (url,)
        ) is not None

    def purgar(self, antes_de: str) -> None:
        """Borra los fragmentos publicados antes de la fecha ISO."""
        self._escribir("DELETE FROM documento WHERE fecha_publicacion < %s", (antes_de,))

    def alta_fuente(self, nombre: str, dominio: str, demora_rastreo_s: float) -> None:
        """Da de alta la fuente en el catálogo si no está, sin corrida todavía:
        los fragmentos la referencian, así que va antes que ellos."""
        self._escribir(
            "INSERT INTO fuente_oficial (nombre, dominio, demora_rastreo_s) "
            "VALUES (%s, %s, %s) ON CONFLICT (nombre) DO NOTHING",
            (nombre, dominio, demora_rastreo_s),
        )

    def registrar_corrida(
        self, nombre: str, dominio: str, demora_rastreo_s: float, fecha: str
    ) -> None:
        """Da de alta la fuente en el catálogo o la actualiza con su corrida."""
        self._escribir(
            "INSERT INTO fuente_oficial (nombre, dominio, demora_rastreo_s, ultima_corrida) "
            "VALUES (%s, %s, %s, %s) ON CONFLICT (nombre) DO UPDATE SET "
            "dominio = excluded.dominio, demora_rastreo_s = excluded.demora_rastreo_s, "
            "ultima_corrida = excluded.ultima_corrida",
            (nombre, dominio, demora_rastreo_s, fecha),
        )

    def pausar(self, nombre: str, hasta: str) -> None:
        """Anota hasta cuándo pidió el sitio de la fuente que no se le pida nada
        (el `Retry-After` de un 429), en ISO."""
        self._escribir(
            "UPDATE fuente_oficial SET pausa_hasta = %s WHERE nombre = %s", (hasta, nombre)
        )

    def pausa(self, dominio: str) -> str | None:
        """La pausa más lejana anotada para el dominio; la comparte toda fuente
        del mismo sitio."""
        fila = self._consultar(
            "SELECT MAX(pausa_hasta) FROM fuente_oficial WHERE dominio = %s", (dominio,)
        )
        return fila[0] if fila else None

    def ultima_corrida(self, nombre: str) -> str | None:
        fila = self._consultar(
            "SELECT ultima_corrida FROM fuente_oficial WHERE nombre = %s", (nombre,)
        )
        return fila[0] if fila else None

    def _consultar(self, sql: str, parametros: tuple) -> tuple | None:
        try:
            with self._activo().connection() as conexion:
                return conexion.execute(sql, parametros).fetchone()
        except psycopg.Error as error:
            raise ErrorDelProveedor(f"indice | {error}") from error

    def _escribir(self, sql: str, parametros: tuple) -> None:
        try:
            with self._activo().connection() as conexion:
                conexion.execute(sql, parametros)
        except psycopg.Error as error:
            raise ErrorDelProveedor(f"indice | {error}") from error

    def _activo(self) -> ConnectionPool:
        if self._pool is None:
            raise ErrorDelProveedor(f"indice | inactivo | {self._error_al_abrir}")
        return self._pool
